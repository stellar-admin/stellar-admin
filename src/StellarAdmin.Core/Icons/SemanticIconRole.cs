namespace StellarAdmin.Icons;

/// <summary>
///     The purpose of a built-in component icon.
/// </summary>
public enum SemanticIconRole
{
    /// <summary>
    ///     Omitted breadcrumb levels.
    /// </summary>
    BreadcrumbEllipsis,

    /// <summary>
    ///     The separator between breadcrumb levels.
    /// </summary>
    BreadcrumbSeparator,

    /// <summary>
    ///     Navigation to the next carousel slide.
    /// </summary>
    CarouselNext,

    /// <summary>
    ///     Navigation to the previous carousel slide.
    /// </summary>
    CarouselPrevious,

    /// <summary>
    ///     A selected checkbox.
    /// </summary>
    CheckboxSelected,

    /// <summary>
    ///     A selected questionnaire choice.
    /// </summary>
    ChoiceSelected,

    /// <summary>
    ///     An action that dismisses a surface.
    /// </summary>
    Close,

    /// <summary>
    ///     An indicator that a select can open.
    /// </summary>
    DropdownIndicator,

    /// <summary>
    ///     An animated loading indicator.
    /// </summary>
    Loading,

    /// <summary>
    ///     A selected checkbox or radio menu item.
    /// </summary>
    MenuItemSelected,

    /// <summary>
    ///     The separator between one-time code groups.
    /// </summary>
    OtpSeparator,

    /// <summary>
    ///     Omitted pages in pagination.
    /// </summary>
    PaginationEllipsis,

    /// <summary>
    ///     Navigation to the first page.
    /// </summary>
    PaginationFirst,

    /// <summary>
    ///     Navigation to the last page.
    /// </summary>
    PaginationLast,

    /// <summary>
    ///     Navigation to the next page.
    /// </summary>
    PaginationNext,

    /// <summary>
    ///     Navigation to the previous page.
    /// </summary>
    PaginationPrevious,

    /// <summary>
    ///     A selected radio input.
    /// </summary>
    RadioSelected,

    /// <summary>
    ///     Navigation to the end of a scrolling message list.
    /// </summary>
    ScrollToEnd,

    /// <summary>
    ///     An ascending sort order.
    /// </summary>
    SortAscending,

    /// <summary>
    ///     A descending sort order.
    /// </summary>
    SortDescending,

    /// <summary>
    ///     A sortable column without an active sort direction.
    /// </summary>
    SortUnsorted,

    /// <summary>
    ///     An indicator that a nested menu can open.
    /// </summary>
    SubmenuIndicator,

    /// <summary>
    ///     An action that toggles the sidebar.
    /// </summary>
    ToggleSidebar,
}
