namespace StellarAdmin.Resources;

/// <summary>
///     Specifies the direction in which resources are sorted.
/// </summary>
public enum ResourceSortDirection
{
    /// <summary>
    ///     Sorts values from lowest to highest.
    /// </summary>
    Ascending,

    /// <summary>
    ///     Sorts values from highest to lowest.
    /// </summary>
    Descending,
}
