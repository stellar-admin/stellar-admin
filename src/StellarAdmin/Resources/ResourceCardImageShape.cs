namespace StellarAdmin.Resources;

/// <summary>
///     Specifies the aspect ratio of the image on the cards of a cards data layout.
/// </summary>
public enum ResourceCardImageShape
{
    /// <summary>
    ///     A 16:9 image.
    /// </summary>
    Widescreen,

    /// <summary>
    ///     A 21:9 image.
    /// </summary>
    Banner,

    /// <summary>
    ///     A 4:3 image.
    /// </summary>
    Landscape,

    /// <summary>
    ///     A square image.
    /// </summary>
    Square,
}
