namespace StellarAdmin.Dashboard;

/// <summary>
///     A theme preset supplied with StellarAdmin.
/// </summary>
public enum DashboardThemePreset
{
    /// <summary>
    ///     The default theme.
    /// </summary>
    Default,

    /// <summary>
    ///     Warm paper and an indigo accent, with roomier controls and tactile buttons.
    /// </summary>
    Ledger,

    /// <summary>
    ///     Dense and sharp, with strong lines and an orange accent.
    /// </summary>
    Ops,

    /// <summary>
    ///     Pill controls, roomy spacing and a violet accent.
    /// </summary>
    Soft,
}
