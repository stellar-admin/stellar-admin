namespace StellarAdmin.UI;

/// <summary>
///     Specifies a part that a control's field renders around the control.
/// </summary>
public enum FieldPart
{
    /// <summary>
    ///     The field's label.
    /// </summary>
    Label,

    /// <summary>
    ///     The field's description text.
    /// </summary>
    Description,

    /// <summary>
    ///     The field's validation error message.
    /// </summary>
    Error,
}
