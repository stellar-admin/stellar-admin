namespace StellarAdmin.UI;

/// <summary>
///     Specifies how a checkbox group displays its options.
/// </summary>
public enum CheckboxGroupVariant
{
    /// <summary>
    ///     The options show as a list.
    /// </summary>
    Default,

    /// <summary>
    ///     The options show as selectable cards.
    /// </summary>
    ChoiceCard,
}
