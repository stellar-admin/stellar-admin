namespace StellarAdmin.UI;

/// <summary>
///     How a display field arranges its label and value.
/// </summary>
[GenerateDataAttributeText]
public enum DisplayFieldOrientation
{
    /// <summary>
    ///     Places the label above the value.
    /// </summary>
    Vertical,

    /// <summary>
    ///     Places the label beside the value.
    /// </summary>
    Horizontal,
}
