namespace StellarAdmin.UI;

/// <summary>
///     How the fields in a details list arrange their labels and values.
/// </summary>
public enum DetailsOrientation
{
    /// <summary>
    ///     Places each label above its value.
    /// </summary>
    Vertical,

    /// <summary>
    ///     Places each label beside its value.
    /// </summary>
    Horizontal,
}
