namespace StellarAdmin.UI;

/// <summary>
///     Specifies which generated slider marks show their value.
/// </summary>
public enum SliderMarkLabels
{
    /// <summary>
    ///     No mark shows its value.
    /// </summary>
    None,

    /// <summary>
    ///     The marks at the minimum and maximum show their value.
    /// </summary>
    Ends,

    /// <summary>
    ///     Every mark shows its value.
    /// </summary>
    All,
}
