namespace StellarAdmin.UI;

/// <summary>
///     Specifies the size of a button.
/// </summary>
public enum ButtonSize
{
    /// <summary>
    ///     The standard size.
    /// </summary>
    Default,

    /// <summary>
    ///     An extra-small size.
    /// </summary>
    ExtraSmall,

    /// <summary>
    ///     A small size.
    /// </summary>
    Small,

    /// <summary>
    ///     A large size.
    /// </summary>
    Large,

    /// <summary>
    ///     A square size for a single icon.
    /// </summary>
    Icon,

    /// <summary>
    ///     An extra-small square size for a single icon.
    /// </summary>
    IconExtraSmall,

    /// <summary>
    ///     A small square size for a single icon.
    /// </summary>
    IconSmall,

    /// <summary>
    ///     A large square size for a single icon.
    /// </summary>
    IconLarge,
}
