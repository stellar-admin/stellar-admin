namespace StellarAdmin.UI;

/// <summary>
///     Specifies the side of its trigger that a tooltip appears on.
/// </summary>
[GenerateDataAttributeText]
public enum TooltipSide
{
    /// <summary>
    ///     Above the trigger.
    /// </summary>
    Top,

    /// <summary>
    ///     To the right of the trigger.
    /// </summary>
    Right,

    /// <summary>
    ///     Below the trigger.
    /// </summary>
    Bottom,

    /// <summary>
    ///     To the left of the trigger.
    /// </summary>
    Left,
}
