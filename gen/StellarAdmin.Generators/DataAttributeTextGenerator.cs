using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace StellarAdmin.Generators;

// Generates GetDataAttributeText() for the enums marked [GenerateDataAttributeText]: a switch that
// returns each member's [DataAttributeText] value, or its name in kebab-case.
[Generator]
public class DataAttributeTextGenerator : IIncrementalGenerator
{
    private const string AttributesNamespace = "StellarAdmin.Generators";

    private const string GenerateAttributeName =
        AttributesNamespace + ".GenerateDataAttributeTextAttribute";

    private const string MemberAttributeName = AttributesNamespace + ".DataAttributeTextAttribute";

    // Conditional keeps the attributes out of the compiled assembly's metadata
    private const string AttributesSource = """
        // <auto-generated/>
        namespace StellarAdmin.Generators;

        [global::System.AttributeUsage(global::System.AttributeTargets.Enum)]
        [global::System.Diagnostics.Conditional("STELLARADMIN_GENERATORS")]
        internal sealed class GenerateDataAttributeTextAttribute : global::System.Attribute { }

        [global::System.AttributeUsage(global::System.AttributeTargets.Field)]
        [global::System.Diagnostics.Conditional("STELLARADMIN_GENERATORS")]
        internal sealed class DataAttributeTextAttribute : global::System.Attribute
        {
            public DataAttributeTextAttribute(string text)
            {
                Text = text;
            }

            public string Text { get; }
        }

        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(postInitializationContext =>
            postInitializationContext.AddSource(
                "DataAttributeTextAttributes.g.cs",
                AttributesSource
            )
        );

        // The source is a string, so an unchanged enum's output stays cached
        var sources = context.SyntaxProvider.ForAttributeWithMetadataName(
            GenerateAttributeName,
            static (node, _) => node is EnumDeclarationSyntax,
            static (attributeContext, _) =>
                WriteSource((INamedTypeSymbol)attributeContext.TargetSymbol)
        );

        context.RegisterSourceOutput(
            sources,
            static (sourceContext, source) => sourceContext.AddSource(source.HintName, source.Text)
        );
    }

    internal static string ToKebabCase(string name)
    {
        var builder = new StringBuilder(name.Length + 4);
        for (var i = 0; i < name.Length; i++)
        {
            var character = name[i];
            if (i > 0 && char.IsUpper(character))
            {
                var previous = name[i - 1];
                var startsWord = !char.IsUpper(previous);
                var endsAcronym =
                    char.IsUpper(previous) && i + 1 < name.Length && char.IsLower(name[i + 1]);
                if (startsWord || endsAcronym)
                {
                    builder.Append('-');
                }
            }

            builder.Append(char.ToLowerInvariant(character));
        }

        return builder.ToString();
    }

    private static (string HintName, string Text) WriteSource(INamedTypeSymbol enumSymbol)
    {
        var enumName = enumSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var className = enumSymbol.Name + "DataAttributeText";
        var containingNamespace = enumSymbol.ContainingNamespace.IsGlobalNamespace
            ? null
            : enumSymbol.ContainingNamespace.ToDisplayString();

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        if (containingNamespace != null)
        {
            source.AppendLine($"namespace {containingNamespace};");
            source.AppendLine();
        }

        source.AppendLine($"internal static class {className}");
        source.AppendLine("{");
        source.AppendLine($"    extension({enumName} value)");
        source.AppendLine("    {");
        source.AppendLine("        public string GetDataAttributeText() =>");
        source.AppendLine("            value switch");
        source.AppendLine("            {");

        // A member that repeats another's value is the same case, so the first one wins
        var values = new HashSet<object>();
        foreach (var member in enumSymbol.GetMembers())
        {
            if (
                member is not IFieldSymbol { HasConstantValue: true } field
                || !values.Add(field.ConstantValue!)
            )
            {
                continue;
            }

            var text = GetText(field) ?? ToKebabCase(field.Name);
            source.AppendLine(
                $"                {enumName}.{field.Name} => {SymbolDisplay.FormatLiteral(text, true)},"
            );
        }

        source.AppendLine("                _ => string.Empty,");
        source.AppendLine("            };");
        source.AppendLine("    }");
        source.AppendLine("}");

        var hintName = enumSymbol
            .ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
            .Replace("global::", string.Empty);
        return ($"{hintName}.DataAttributeText.g.cs", source.ToString());
    }

    private static string? GetText(IFieldSymbol field)
    {
        foreach (var attribute in field.GetAttributes())
        {
            if (
                attribute.AttributeClass?.ToDisplayString() == MemberAttributeName
                && attribute.ConstructorArguments.Length == 1
                && attribute.ConstructorArguments[0].Value is string text
            )
            {
                return text;
            }
        }

        return null;
    }
}
